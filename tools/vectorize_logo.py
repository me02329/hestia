"""Vectorizes the Hestia emblem (gold figure + flame on a dark background) into:
  branding/hestia-logo.svg          transparent SVG
  branding/hestia-logo.png          transparent PNG (1024 px, from the source pixels)
  app/res/drawable/hestia_logo.xml  Android VectorDrawable drawn by the home screen and the settings
Each color is separated into a mask and traced with potrace (dev-only: pip install potracer numpy pillow).
Usage: python3 tools/vectorize_logo.py branding/hestia-emblem-source.png
"""
import os
import re
import sys

import numpy as np
import potrace
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def masks(rgb):
    """Gold and flame masks (0..1 coverage, anti-aliased edges kept) from the dark background."""
    px = rgb.astype(np.float32)
    bg = np.median(px[:8, :8].reshape(-1, 3), axis=0)
    lum = px.max(axis=2)
    cover = np.clip((lum - bg.max()) / (225 - bg.max()), 0, 1)
    r, g = px[..., 0], px[..., 1]
    flame = (g < r * 0.62) & (r > 120)
    return cover * ~flame, cover * flame


def color(rgb, mask):
    sel = rgb[mask > 0.9]
    return "#%02X%02X%02X" % tuple(int(v) for v in np.median(sel, axis=0))


def trace(mask):
    """One SVG path (even-odd: holes are their own contours) for a 0..1 mask, in source pixel units."""
    out = []
    for curve in potrace.Bitmap(~(mask > 0.5)).trace(turdsize=6, alphamax=1.0, opticurve=True, opttolerance=0.2):
        p = curve.start_point
        out.append("M%.1f %.1f" % (p.x, p.y))
        for seg in curve.segments:
            if seg.is_corner:
                out.append("L%.1f %.1f L%.1f %.1f" % (seg.c.x, seg.c.y, seg.end_point.x, seg.end_point.y))
            else:
                out.append("C%.1f %.1f %.1f %.1f %.1f %.1f" % (seg.c1.x, seg.c1.y, seg.c2.x, seg.c2.y,
                                                               seg.end_point.x, seg.end_point.y))
        out.append("Z")
    return " ".join(out)


def main(source):
    rgb = np.array(Image.open(source).convert("RGB"))
    gold, flame = masks(rgb)
    layers = [(color(rgb, gold), trace(gold)), (color(rgb, flame), trace(flame))]

    ys, xs = np.nonzero((gold + flame) > 0.5)
    pad = 12
    x0, y0 = int(xs.min()) - pad, int(ys.min()) - pad
    w, h = int(xs.max()) + pad - x0, int(ys.max()) + pad - y0

    os.makedirs(os.path.join(ROOT, "branding"), exist_ok=True)
    svg = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %d %d" width="%d" height="%d">' % (w, h, w, h)]
    for fill, d in layers:
        svg.append('<path fill="%s" fill-rule="evenodd" transform="translate(%d %d)" d="%s"/>' % (fill, -x0, -y0, d))
    svg.append("</svg>")
    open(os.path.join(ROOT, "branding/hestia-logo.svg"), "w").write("\n".join(svg) + "\n")

    vd = ['<?xml version="1.0" encoding="utf-8"?>',
          '<!-- Generated by tools/vectorize_logo.py: the Hestia emblem, transparent background. -->',
          '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
          '    android:width="%ddp" android:height="%ddp"' % (w // 4, h // 4),
          '    android:viewportWidth="%d" android:viewportHeight="%d">' % (w, h)]
    vd.append('    <group android:translateX="%d" android:translateY="%d">' % (-x0, -y0))
    for fill, d in layers:
        vd.append('        <path android:fillColor="%s" android:fillType="evenOdd"' % fill)
        vd.append('            android:pathData="%s"/>' % d)
    vd.append('    </group>')
    vd.append('</vector>')
    open(os.path.join(ROOT, "app/res/drawable/hestia_logo.xml"), "w").write("\n".join(vd) + "\n")

    # Transparent PNG straight from the pixels (coverage as alpha), cropped like the vector.
    alpha = np.clip(gold + flame, 0, 1)
    rgba = np.dstack([rgb, (alpha * 255).astype(np.uint8)])[y0:y0 + h, x0:x0 + w]
    png = Image.fromarray(rgba, "RGBA")
    png.thumbnail((1024, 1024), Image.LANCZOS)
    png.save(os.path.join(ROOT, "branding/hestia-logo.png"), optimize=True)
    print("gold %s, flame %s, %d x %d, %d KB of path data" % (layers[0][0], layers[1][0], w, h,
                                                            sum(len(d) for _, d in layers) // 1024))


if __name__ == "__main__":
    main(sys.argv[1])
